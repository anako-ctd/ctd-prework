# This script gives clothing advice based on the weather.

city = input("What city are you in? ")
temp = int(input("What is the temperature in Celsius? "))

if temp < 15:
    advice = "bring a jacket"
else:
    advice = "shorts and a t-shirt are fine"

print("It is " + str(temp) + " degrees Celsius in " + city + ".")
print("My advice: " + advice + ".")

